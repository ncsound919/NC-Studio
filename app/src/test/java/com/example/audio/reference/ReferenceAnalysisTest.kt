package com.example.audio.reference

import com.example.audio.engine.WavAudioIO
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File
import kotlin.math.PI
import kotlin.math.sin

/**
 * The analyser is the part of the reference feature that has to be right: if the
 * loudness number is wrong, the A/B level match is wrong, and a louder side
 * always wins. These tests pin the implementation to BS.1770-4 (calibration and
 * gating), to the shape of the measurement (band balance, width), and - when the
 * fixtures are on disk - to pyloudnorm's numbers on real commercial masters.
 *
 * Fixtures: the 30 s WAV excerpts in `test_output/ref_wav`, generated by the
 * procedure in REFERENCE_AB.md (decode excerpts of the reference tracks, then
 * measure them with pyloudnorm). Without them the cross-check is skipped,
 * never faked.
 */
class ReferenceAnalysisTest {

    private val rate = 48000

    private fun sine(frames: Int, amplitude: Float, frequency: Double = 997.0): FloatArray =
        FloatArray(frames) { i -> (amplitude * sin(2.0 * PI * frequency * i / rate)).toFloat() }

    private fun toStereo(mono: FloatArray): FloatArray {
        val out = FloatArray(mono.size * 2)
        for (i in mono.indices) {
            out[i * 2] = mono[i]
            out[i * 2 + 1] = mono[i]
        }
        return out
    }

    private fun amplitudeFor(dbFs: Double): Float = Math.pow(10.0, dbFs / 20.0).toFloat()

    // ---------------------------------------------------------------- loudness

    @Test
    fun `a 997 Hz sine at -23 dBFS reads what pyloudnorm reads`() {
        // Two numbers pin the whole chain (K-weighting, gating, channel sum):
        // pyloudnorm measures -26.0517 for a mono -23 dBFS 997 Hz sine and
        // -23.0414 for the same signal in both channels. The 3 dB difference is
        // the two channels summing; the +0.65 dB above a raw RMS reading is the
        // K-weighting's gain at 1 kHz, which is what the -0.691 offset repays.
        val mono = sine(rate * 5, amplitudeFor(-23.0))
        val monoStats = LoudnessAnalyzer(rate).analyze(mono, channels = 1)
        assertEquals("mono reading", -26.0517f, monoStats.integratedLufs, 0.05f)

        val stereoStats = LoudnessAnalyzer(rate).analyze(toStereo(mono), channels = 2)
        assertEquals("dual-mono reading (the standard's calibration point)", -23.0414f, stereoStats.integratedLufs, 0.05f)
        assertEquals(3.01f, stereoStats.integratedLufs - monoStats.integratedLufs, 0.05f)
    }

    @Test
    fun `a quiet section below the relative gate does not drag the integrated value down`() {
        // pyloudnorm reads -20.2074 for 4 s at -20 dBFS followed by 16 s at -55 dBFS
        // (dual mono). Ungated, the same material would average out near -24.2,
        // so this one number proves the relative gate is doing its job.
        val loud = sine(rate * 4, amplitudeFor(-20.0))
        val quiet = sine(rate * 16, amplitudeFor(-55.0))
        val stats = LoudnessAnalyzer(rate).analyze(toStereo(loud + quiet), channels = 2)
        assertEquals("gated reading", -20.2074f, stats.integratedLufs, 0.15f)
        assertTrue("the quiet tail must be gated out, not averaged in", stats.integratedLufs > -21.5f)
    }

    @Test
    fun `silence reads as silence and never as a number that looks like audio`() {
        val stats = LoudnessAnalyzer(rate).analyze(FloatArray(rate * 2), channels = 2)
        assertEquals(-60f, stats.integratedLufs, 0.01f)
        assertEquals(-120f, stats.truePeakDb, 0.01f)
    }

    @Test
    fun `clips shorter than one gating block still measure their own loudness`() {
        // pyloudnorm refuses anything under 400 ms; our analyser treats the whole
        // clip as one window, which is the only useful answer offline.
        val clip = sine(rate / 40, amplitudeFor(-20.0)) // 25 ms, dual mono
        val stats = LoudnessAnalyzer(rate).analyze(toStereo(clip), channels = 2)
        assertEquals("-20 dBFS dual mono, K-weighted", -20.04f, stats.integratedLufs, 0.3f)
    }

    // -------------------------------------------------------------- true peak

    @Test
    fun `true peak catches inter sample peaks that sample peak misses`() {
        // A quarter-rate sine at 45 degrees: every sample lands on +-0.7071
        // (-3.01 dBFS) while the waveform between samples reaches full scale.
        val n = rate * 2
        val signal = FloatArray(n) { i ->
            sin(2.0 * PI * (rate / 4.0) * i / rate + PI / 4.0).toFloat()
        }
        val stats = LoudnessAnalyzer(rate).analyze(toStereo(signal), channels = 2)
        assertTrue("sample peak should read about -3 dBFS", stats.samplePeakDb in -3.3f..-2.7f)
        assertTrue(
            "true peak (${stats.truePeakDb}) must be well above the sample peak (${stats.samplePeakDb})",
            stats.truePeakDb - stats.samplePeakDb > 2.5f
        )
        // A 4x `resample_poly` reference reads 0.12 dBTP here; 16 taps per phase
        // land within 0.15 dB of it.
        assertTrue("true peak should land near 0 dBTP", stats.truePeakDb in -0.35f..0.25f)
    }

    // --------------------------------------------------------- tonal balance

    @Test
    fun `pink noise reads flat across the octave bands`() {
        // Pink noise carries equal energy per octave, so a correct octave-band
        // analyser must show all ten bands at about -10 dB (one tenth of the
        // total each). White noise would slope up 3 dB per octave and prove
        // nothing about the band edges.
        val pink = pinkNoise(rate * 4)
        val bands = SpectrumBalanceAnalyzer().analyze(toStereo(pink), rate, 2)
        assertEquals(SpectrumBalanceAnalyzer.BAND_CENTERS_HZ.size, bands.size)
        bands.forEachIndexed { index, db ->
            assertTrue(
                "band ${SpectrumBalanceAnalyzer.BAND_LABELS[index]} read $db dB, expected about -10 dB",
                db in -13.5f..-6.5f
            )
        }
    }

    /** White noise through the usual three-pole pink approximation. */
    private fun pinkNoise(frames: Int): FloatArray {
        val random = java.util.Random(7)
        var b0 = 0.0; var b1 = 0.0; var b2 = 0.0
        return FloatArray(frames) {
            val white = random.nextDouble() * 2.0 - 1.0
            b0 = 0.99765 * b0 + white * 0.0990460
            b1 = 0.96300 * b1 + white * 0.2965164
            b2 = 0.57000 * b2 + white * 1.0526913
            ((b0 + b1 + b2 + white * 0.1848) * 0.05).toFloat()
        }
    }

    @Test
    fun `a 1 kHz tone lands in the 1 kHz band`() {
        val tone = FloatArray(rate * 2) { i -> (0.3 * sin(2.0 * PI * 1000.0 * i / rate)).toFloat() }
        val bands = SpectrumBalanceAnalyzer().analyze(toStereo(tone), rate, 2)
        val loudest = bands.indices.maxByOrNull { bands[it] }!!
        assertEquals("expected the 1 kHz band", 5, loudest)
    }

    // ----------------------------------------------------------- stereo image

    @Test
    fun `mono content is a single image, anti phase inverts the correlation`() {
        val n = rate
        val left = FloatArray(n) { i -> (0.3 * sin(2.0 * PI * 440.0 * i / rate)).toFloat() }

        val mono = FloatArray(n * 2)
        val antiPhase = FloatArray(n * 2)
        val hardLeft = FloatArray(n * 2)
        for (i in 0 until n) {
            mono[i * 2] = left[i]; mono[i * 2 + 1] = left[i]
            antiPhase[i * 2] = left[i]; antiPhase[i * 2 + 1] = -left[i]
            hardLeft[i * 2] = left[i]; hardLeft[i * 2 + 1] = 0f
        }

        val monoImage = StereoImageAnalyzer.analyze(mono, 2)
        assertEquals(1f, monoImage.correlation, 0.001f)
        assertTrue("identical channels have no side energy", monoImage.widthDb <= -50f)

        val antiImage = StereoImageAnalyzer.analyze(antiPhase, 2)
        assertEquals(-1f, antiImage.correlation, 0.001f)

        val leftImage = StereoImageAnalyzer.analyze(hardLeft, 2)
        assertEquals(0f, leftImage.correlation, 0.001f)
        assertEquals("hard-panned content is all side", 0f, leftImage.widthDb, 0.1f)
    }

    // -------------------------------------------------- real commercial mixes

    @Test
    fun `real masters match pyloudnorm and a 4x true peak reference`() {
        val directory = referenceWavDirectory()
        val fixtures = listOf(
            // file -> (pyloudnorm integrated LUFS, scipy 4x true peak dBTP)
            "abracadabra_30s.wav" to (-5.462f to 0.94f),
            "contour_30s.wav" to (-13.367f to -0.33f),
            "moveyourbody_30s.wav" to (-7.775f to 0.84f),
            "teen_spirit_30s.wav" to (-7.452f to 0.24f)
        )
        val available = fixtures.filter { File(directory, it.first).exists() }
        assumeTrue(
            "reference WAV fixtures not found in $directory (see REFERENCE_AB.md)",
            available.isNotEmpty()
        )

        for ((name, expected) in available) {
            val wav = WavAudioIO.readWavFile(File(directory, name))!!
            val profile = ReferenceProfiler.analyze(wav.samples, wav.sampleRate, label = name)
            assertEquals("$name integrated LUFS vs pyloudnorm", expected.first, profile.integratedLufs, 0.15f)
            assertEquals("$name true peak vs 4x oversampled reference", expected.second, profile.truePeakDb, 0.25f)
            assertTrue("$name should report a width", profile.widthDb > -30f)
        }
    }

    private fun referenceWavDirectory(): File {
        val fromProperty = System.getProperty("nc.reference.wav.dir")
        val candidates = listOfNotNull(
            fromProperty?.let { File(it) },
            System.getenv("NC_REFERENCE_WAV_DIR")?.let { File(it) },
            File("../../../test_output/ref_wav"),
            File("../../test_output/ref_wav"),
            File("test_output/ref_wav")
        )
        return candidates.firstOrNull { it.isDirectory } ?: candidates.first()
    }
}
